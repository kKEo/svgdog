#!/usr/bin/env bash
# Generates docs/guide/operator/reference/rules.md from `svgdog rules` and
# `svgdog rules --explain ID`. Deterministic: no dates, rules in catalogue order.
# Usage: docs/gen-rules.sh [path-to-svgdog]   (default: target/release/svgdog, or $SVGDOG)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
bin="${1:-${SVGDOG:-$root/target/release/svgdog}}"
out="$root/docs/guide/operator/reference/rules.md"
[ -x "$bin" ] || { echo "svgdog binary not found at $bin; run cargo build --release" >&2; exit 1; }
mkdir -p "$(dirname "$out")"
SVGDOG_BIN="$bin" python3 -I - "$out" <<'PY'
import json, subprocess, sys, os

bin_ = os.environ["SVGDOG_BIN"]

def run(*args):
    r = subprocess.run([bin_, "--format", "json", "--no-config", "--quiet", *args],
                       check=True, capture_output=True, text=True)
    return json.loads(r.stdout)

rules = run("rules")["rules"]
titles = {"structure": "Structure", "geometry": "Geometry",
          "portability": "Portability", "accessibility": "Accessibility"}
def esc(t):
    return str(t).replace("|", "\\|").replace("<", "&lt;")

out = []
w = out.append
w("# Rules catalogue\n")
w("<!-- Generated by docs/gen-rules.sh from `svgdog rules`. Do not edit: change the source and run docs/gen-rules.sh. -->\n")
w(f"svgdog ships {len(rules)} rules that check any SVG, whether or not svgdog drew it. "
  "This page lists each rule with its default severity (the `docs` profile), whether `svgdog fix` can repair it, "
  "its thresholds and a failing and a passing example. "
  "Severities and thresholds can be changed in [`svgdog.toml`](configuration.md).\n")
w("The autofix column is `none` (no fix), `safe` (applied by `svgdog fix`) or `unsafe` (applied only with `--unsafe`).\n")
w("## Summary\n")
w("| Group | Rule | Default severity | Autofix | Fails when |")
w("|---|---|---|---|---|")
for r in rules:
    w(f"| {r['group']} | `{r['id']}` | {r['severity']} | {r['autofix']} | {esc(r['fails_when'])} |")
w("")
for g in ["structure", "geometry", "portability", "accessibility"]:
    w(f"## {titles[g]} rules\n")
    for r in [x for x in rules if x["group"] == g]:
        d = run("rules", "--explain", r["id"])["rule"]
        w(f"### `{d['id']}`\n")
        w(f"Default severity **{d['severity']}**. Fails when: {esc(d['fails_when'])}. Autofix: {esc(d['autofix_note'])}.\n")
        w(esc(d["rationale"]) + "\n")
        if d["options"]:
            w("| Option | Default | Meaning |")
            w("|---|---|---|")
            for o in d["options"]:
                w(f"| `{o['key']}` | {o['default']} | {esc(o['about'])} |")
            w("")
            w(f"Set in `svgdog.toml`: `[rules] {d['id']} = {{ {d['options'][0]['key']} = {d['options'][0]['default']} }}`.\n")
        if d["example_config"]:
            w("The examples assume this `svgdog.toml`:\n")
            w("```toml\n" + d["example_config"].rstrip("\n") + "\n```\n")
        w("Fails:\n")
        w("```xml\n" + d["fail"].rstrip("\n") + "\n```\n")
        w("Passes:\n")
        w("```xml\n" + d["pass"].rstrip("\n") + "\n```\n")
w("## Suppression diagnostics\n")
w("A malformed `svgdog-disable` comment is reported as `invalid-suppression` (always an error). "
  "It is not part of the catalogue above and cannot itself be configured or suppressed. See [Configuration](configuration.md#suppressing-a-rule-on-one-element).\n")
text = "\n".join(out).rstrip("\n") + "\n"
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write(text)
PY
echo "wrote $out"
