//! Portability rules: the file renders the same outside a browser.

use serde_json::json;

use super::Ctx;
use crate::svg::text::{self, GENERIC, families};
use crate::svg::{Kind, href};
use crate::util::{fmt, num};

const EDITOR_NS: &[&str] = &[
    "inkscape.org", "sodipodi.sourceforge.net", "ns.adobe.com", "bohemiancoding.com", "figma.com",
    "schemas.microsoft.com/visio", "serif.com", "boxy-svg.com", "creativecommons.org/ns", "purl.org/dc",
    "www.w3.org/1999/02/22-rdf-syntax-ns", "vectornator.io", "www.corel.com",
];

const GENERATOR_WORDS: &[&str] = &["generator", "created with", "created by", "exported", "generated by"];

fn external(url: &str) -> bool {
    let u = url.trim();
    !(u.is_empty() || u.starts_with('#') || u.to_ascii_lowercase().starts_with("data:"))
}

/// External `url(...)` and `@import` targets in CSS or attribute text.
fn external_urls(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(i) = rest.find("url(") {
        let inner = rest[i + 4..].split(')').next().unwrap_or("").trim().trim_matches(|c| c == '"' || c == '\'');
        if external(inner) {
            out.push(inner.to_string());
        }
        rest = &rest[i + 4..];
    }
    let mut rest = text;
    while let Some(i) = rest.find("@import") {
        let stmt = rest[i + 7..].split(';').next().unwrap_or("").trim();
        if !stmt.starts_with("url(") {
            out.push(stmt.trim_matches(|c| c == '"' || c == '\'').to_string());
        }
        rest = &rest[i + 7..];
    }
    out
}

fn css_features(text: &str) -> Vec<&'static str> {
    let mut f = Vec::new();
    let custom_decl = text.split(['{', ';']).any(|d| d.trim_start().starts_with("--"));
    if text.contains("var(") || custom_decl {
        f.push("custom properties");
    }
    // A dark-mode override is fine: a renderer that skips it still shows the complete light drawing.
    if text.matches("@media").count() > text.matches("@media (prefers-color-scheme:").count() {
        f.push("media queries");
    }
    if text.contains("mix-blend-mode") {
        f.push("blend modes");
    }
    f
}

fn css_animation(text: &str) -> bool {
    text.contains("@keyframes") || text.split(['{', ';']).any(|d| d.trim_start().starts_with("animation"))
}

fn lacks_generic(value: &str) -> bool {
    let v = value.trim();
    if v == "inherit" || v.contains("var(") {
        return false;
    }
    let list = families(v);
    !list.is_empty() && !list.iter().any(|f| GENERIC.contains(&f.as_str()))
}

pub fn run(ctx: &mut Ctx) {
    let scene = ctx.scene;
    let root = scene.root;

    if ctx.on("file-too-large") {
        let max_kb = ctx.set.opt("file-too-large", "max_kb");
        let kb = ctx.bytes as f64 / 1000.0;
        if kb > max_kb {
            ctx.push("file-too-large", root, None, format!("The file is {} kB; the limit is {} kB.", fmt(kb), fmt(max_kb)), vec![("size_kb", num(kb)), ("max_kb", num(max_kb))]);
        }
    }

    if ctx.on("fixed-size") && root.tag_name().name() == "svg" {
        let abs = |name: &str| root.attribute(name).filter(|v| !v.trim().ends_with('%') && v.trim() != "auto");
        let (w, h) = (abs("width"), abs("height"));
        if w.is_some() || h.is_some() {
            let what = match (w, h) {
                (Some(w), Some(h)) => format!("width=\"{w}\" and height=\"{h}\""),
                (Some(w), None) => format!("width=\"{w}\""),
                (None, Some(h)) => format!("height=\"{h}\""),
                _ => unreachable!(),
            };
            ctx.push("fixed-size", root, None, format!("The root sets {what}, so the image cannot scale to the page."), vec![("width", json!(w)), ("height", json!(h))]);
            // Without a viewBox the size is all there is; viewbox-missing has to be fixed first.
            if scene.viewbox.is_some() {
                let t = ctx.target(root);
                let ops = [("width", w), ("height", h)].iter().filter(|(_, v)| v.is_some()).map(|(k, _)| json!({ "op": "remove", "target": t, "attr": k })).collect();
                ctx.fix(true, ops);
            }
        }
    }

    if ctx.on("external-resource") {
        for pi in scene.doc.root().children().filter(|n| n.is_pi()) {
            if pi.pi().is_some_and(|p| p.target == "xml-stylesheet") {
                ctx.push("external-resource", root, None, "The file loads a stylesheet through an <?xml-stylesheet?> instruction.".into(), vec![]);
            }
        }
    }

    if ctx.on("editor-metadata") {
        let namespaces: Vec<&str> = root.namespaces().filter(|ns| EDITOR_NS.iter().any(|e| ns.uri().contains(e))).filter_map(|ns| ns.name()).collect();
        let comments = scene
            .doc
            .descendants()
            .filter(|n| n.is_comment())
            .filter(|n| {
                let t = n.text().unwrap_or("").to_lowercase();
                GENERATOR_WORDS.iter().any(|k| t.contains(k))
            })
            .count();
        // The spec a drawing was rendered from is its source, not an editor's leftovers.
        let own = |n: &roxmltree::Node| n.attribute("id") == Some(crate::describe::EMBED_ID);
        let metadata = scene.doc.descendants().filter(|n| n.is_element() && n.tag_name().name() == "metadata" && !own(n)).count();
        if !namespaces.is_empty() || comments > 0 || metadata > 0 {
            let mut parts = Vec::new();
            if !namespaces.is_empty() {
                parts.push(format!("editor namespaces ({})", namespaces.join(", ")));
            }
            if comments > 0 {
                parts.push(format!("{comments} generator comment{}", if comments == 1 { "" } else { "s" }));
            }
            if metadata > 0 {
                parts.push(format!("{metadata} <metadata> element{}", if metadata == 1 { "" } else { "s" }));
            }
            ctx.push("editor-metadata", root, None, format!("The file holds {}.", parts.join(", ")), vec![("namespaces", json!(namespaces)), ("comments", json!(comments)), ("metadata_elements", json!(metadata))]);
            let t = ctx.target(root);
            let editor = |n: &roxmltree::Node| n.is_element() && n.tag_name().namespace().is_some_and(|ns| EDITOR_NS.iter().any(|e| ns.contains(e)));
            let mut ops = Vec::new();
            for n in scene.doc.descendants().filter(|n| n.is_element()) {
                let strip = n.tag_name().name() == "metadata" && scene.is_svg(n) && !own(&n) || editor(&n);
                if strip && !n.ancestors().skip(1).any(|a| a.tag_name().name() == "metadata" || editor(&a)) {
                    ops.push(json!({ "op": "remove", "target": ctx.target(n) }));
                }
            }
            for p in &namespaces {
                ops.push(json!({ "op": "remove", "target": "*", "attr": format!("{p}:*") }));
                ops.push(json!({ "op": "remove", "target": t, "attr": format!("xmlns:{p}") }));
            }
            for (i, c) in scene.doc.descendants().filter(|n| n.is_comment()).enumerate() {
                let text = c.text().unwrap_or("").to_lowercase();
                if GENERATOR_WORDS.iter().any(|k| text.contains(k)) {
                    ops.push(json!({ "op": "remove", "target": format!("comment({})", i + 1) }));
                }
            }
            ctx.fix(true, ops);
        }
    }

    for n in scene.doc.descendants().filter(|n| n.is_element()) {
        if !scene.is_svg(n) {
            continue;
        }
        let tag = n.tag_name().name();
        let css: String = if tag == "style" { n.children().filter(|c| c.is_text()).filter_map(|c| c.text()).collect() } else { String::new() };
        let inline = n.attribute("style").unwrap_or("");

        if ctx.on("script-content") {
            if tag == "script" {
                ctx.push("script-content", n, None, "The file contains a <script> element.".into(), vec![]);
                let t = ctx.target(n);
                ctx.fix(true, vec![json!({ "op": "remove", "target": t })]);
            }
            for a in n.attributes() {
                if a.namespace().is_none() && a.name().len() > 2 && a.name().starts_with("on") {
                    ctx.push("script-content", n, None, format!("Event handler attribute '{}' carries script.", a.name()), vec![("attribute", json!(a.name()))]);
                    let t = ctx.target(n);
                    ctx.fix(true, vec![json!({ "op": "remove", "target": t, "attr": a.name() })]);
                }
            }
            if href(n).is_some_and(|h| h.trim().to_ascii_lowercase().starts_with("javascript:")) {
                ctx.push("script-content", n, None, "A link uses a javascript: URL.".into(), vec![]);
                let t = ctx.target(n);
                let attr = if n.attribute("href").is_some() { "href" } else { "xlink:href" };
                ctx.fix(true, vec![json!({ "op": "remove", "target": t, "attr": attr })]);
            }
        }

        if ctx.on("foreign-object") && tag == "foreignObject" {
            let bbox = scene.elems.iter().find(|e| e.node == n).and_then(|e| e.bbox);
            ctx.push("foreign-object", n, bbox, "<foreignObject> content is dropped by many PDF and image pipelines.".into(), vec![]);
        }

        if ctx.on("animation") {
            if matches!(tag, "animate" | "animateTransform" | "animateMotion" | "animateColor" | "set") {
                ctx.push("animation", n, None, format!("<{tag}> animates the drawing."), vec![]);
                let t = ctx.target(n);
                ctx.fix(true, vec![json!({ "op": "remove", "target": t })]);
            }
            if css_animation(&css) || css_animation(inline) {
                ctx.push("animation", n, None, "Styles define a CSS animation.".into(), vec![]);
            }
        }

        if ctx.on("external-resource") {
            let mut urls: Vec<String> = Vec::new();
            if matches!(tag, "image" | "use" | "feImage" | "script" | "textPath" | "linearGradient" | "radialGradient" | "pattern" | "filter")
                && let Some(h) = href(n)
                && external(h)
                && !h.trim().to_ascii_lowercase().starts_with("javascript:")
            {
                urls.push(h.to_string());
            }
            for a in n.attributes().filter(|a| a.namespace().is_none()) {
                urls.extend(external_urls(a.value()));
            }
            urls.extend(external_urls(&css));
            for u in urls {
                let short: String = u.chars().take(80).collect();
                ctx.push("external-resource", n, None, format!("<{tag}> points outside the file: {short}."), vec![("url", json!(short))]);
            }
        }

        if ctx.on("embedded-raster")
            && matches!(tag, "image" | "feImage")
            && let Some(h) = href(n)
        {
            let lower: String = h.trim().chars().take(40).collect::<String>().to_ascii_lowercase();
            if lower.starts_with("data:image/") && !lower.starts_with("data:image/svg") {
                let kb = h.len() as f64 / 1000.0;
                let bbox = scene.elems.iter().find(|e| e.node == n && matches!(e.kind, Kind::Image)).and_then(|e| e.bbox);
                ctx.push("embedded-raster", n, bbox, format!("The image embeds {} kB of base64 raster data.", fmt(kb)), vec![("size_kb", num(kb))]);
            }
        }

        if ctx.on("css-unsupported") {
            let mut features = css_features(&css);
            for f in css_features(inline) {
                if !features.contains(&f) {
                    features.push(f);
                }
            }
            for a in n.attributes().filter(|a| a.namespace().is_none() && a.name() != "style") {
                if a.value().contains("var(") && !features.contains(&"custom properties") {
                    features.push("custom properties");
                }
                if a.name() == "mix-blend-mode" && !features.contains(&"blend modes") {
                    features.push("blend modes");
                }
            }
            if !features.is_empty() {
                ctx.push("css-unsupported", n, None, format!("Styles use {}, which static renderers ignore.", features.join(" and ")), vec![("features", json!(features))]);
            }
        }

        if ctx.on("font-not-portable") {
            let mut declared: Vec<(&str, &str)> = Vec::new();
            if let Some(v) = n.attribute("font-family") {
                declared.push(("attr", v));
            }
            for d in simplecss::DeclarationTokenizer::from(inline) {
                if d.name == "font-family" {
                    declared.push(("style", d.value));
                }
            }
            for (key, v) in declared {
                if lacks_generic(v) {
                    ctx.push("font-not-portable", n, None, format!("font-family \"{}\" has no generic fallback such as sans-serif.", v.trim()), vec![("font_family", json!(v.trim()))]);
                    let generic = if text::classify(Some(v)).0 == text::Class::Mono { "monospace" } else { "sans-serif" };
                    let t = ctx.target(n);
                    ctx.fix(true, vec![json!({ "op": "set", "target": t, key: "font-family", "value": format!("{}, {generic}", v.trim()) })]);
                }
            }
        }
    }

    if ctx.on("font-not-portable") {
        let style_el = scene.doc.descendants().find(|n| n.is_element() && n.tag_name().name() == "style" && scene.is_svg(*n));
        if let Some(style_el) = style_el {
            for r in scene.css.rules() {
                for d in r.declarations.iter().filter(|d| d.name == "font-family") {
                    if lacks_generic(d.value) {
                        let msg = format!("font-family \"{}\" in rule '{}' has no generic fallback such as sans-serif.", d.value.trim(), r.selector);
                        ctx.push("font-not-portable", style_el, None, msg, vec![("font_family", json!(d.value.trim())), ("selector", json!(r.selector.to_string()))]);
                    }
                }
            }
        }
    }
}
