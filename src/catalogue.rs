//! The rule catalogue: ids, default severities, thresholds and worked examples.
//!
//! The examples double as tests: every `fail` must raise its rule and every `pass` must not.

use crate::envelope::Severity;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Group {
    Structure,
    Geometry,
    Portability,
    Accessibility,
}

impl Group {
    pub fn as_str(&self) -> &'static str {
        match self {
            Group::Structure => "structure",
            Group::Geometry => "geometry",
            Group::Portability => "portability",
            Group::Accessibility => "accessibility",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Autofix {
    None,
    Safe,
    Unsafe,
}

impl Autofix {
    pub fn as_str(&self) -> &'static str {
        match self {
            Autofix::None => "none",
            Autofix::Safe => "safe",
            Autofix::Unsafe => "unsafe",
        }
    }
}

pub struct Opt {
    pub key: &'static str,
    pub default: f64,
    pub about: &'static str,
}

pub struct RuleMeta {
    pub id: &'static str,
    pub group: Group,
    pub severity: Severity,
    pub autofix: Autofix,
    pub fails_when: &'static str,
    pub autofix_note: &'static str,
    pub rationale: &'static str,
    pub options: &'static [Opt],
    /// svgdog.toml content the examples assume; empty when the defaults apply.
    pub example_config: &'static str,
    pub fail: &'static str,
    pub pass: &'static str,
}

/// Raised for a malformed `svgdog-disable` comment. Not part of the catalogue and not configurable.
pub const INVALID_SUPPRESSION: &str = "invalid-suppression";

macro_rules! doc {
    ($body:literal) => {
        concat!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 200 100\">\n  <title>Example</title>\n",
            $body,
            "\n</svg>\n"
        )
    };
}

/// A canvas as wide as the default render width, so sizes read as rendered pixels.
macro_rules! wide {
    ($body:literal) => {
        concat!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 720 200\">\n  <title>Example</title>\n",
            $body,
            "\n</svg>\n"
        )
    };
}

